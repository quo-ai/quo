/**
 * Returns `count` random prompts without repeats (uniform). Partial
 * Fisher-Yates over an index map: O(count), no copy/sort of the whole bank.
 */
export function getRandomPrompts(count: number = 4): string[] {
  const n = SUGGESTED_PROMPTS.length;
  const k = Math.max(0, Math.min(Math.floor(count), n));
  // Sparse "virtual array" of swapped indices; untouched slots map to themselves.
  const swapped = new Map<number, number>();
  const result: string[] = [];
  for (let i = 0; i < k; i++) {
    const j = i + Math.floor(Math.random() * (n - i));
    const atJ = swapped.get(j) ?? j;
    swapped.set(j, swapped.get(i) ?? i);
    result.push(SUGGESTED_PROMPTS[atJ]);
  }
  return result;
}

