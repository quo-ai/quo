#!/usr/bin/env python3
"""Regenerate every app/brand bitmap from the Quo logo geometry.

  python3 scripts/generate-brand-assets.py [--store DIR]

Needs ImageMagick 7 (`magick`) built with librsvg. Writes:
  assets/brand/quo-mark.svg            canonical mark (white, transparent gaps)
  assets/images/icon.png               iOS/Expo app icon (1024, full bleed)
  assets/images/adaptive-icon-foreground.png / -monochrome.png (Expo adaptive)
  assets/images/splash-icon.png        splash mark (white on transparent)
  assets/images/notification-icon.png  Android status-bar glyph
  android/app/src/main/res/...         launcher mipmaps, splash logo,
                                       notification icons (android/ is not
                                       regenerated by prebuild)
  DIR/play-icon-512.png                Play Store listing icon (only with --store;
                                       store listing assets live outside this repo)

Geometry and safe zones:
  * Adaptive icon: 108dp canvas, content kept inside the 66dp safe circle.
  * Android 12 splash: 288dp canvas, mark inside the 192dp circle.
  * Notification: 24dp, white alpha silhouette, no sparkles (too small).
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDIGO = '#3B2EFF'

Q_OUTER = ('M 490 200 C 682 200 812 340 812 505 C 812 592 784 652 745 696 L 803 828 Q 816 862 780 856 '
           'L 600 798 C 565 808 528 812 490 812 C 298 812 175 680 175 505 C 175 330 298 200 490 200 Z')
Q_INNER = ('M 495 320 C 380 320 302 400 302 510 C 302 620 380 700 495 700 C 525 700 552 695 575 688 '
           'L 652 734 Q 674 744 667 721 L 640 668 C 670 630 688 580 688 510 C 688 400 610 320 495 320 Z')
RING_FRONT = 'M -455 0 A 455 95 0 0 0 455 0'
RING_T = 'translate(505 470) rotate(-18)'
SPARKLES = [
    'M 238 128 C 243 166 254 178 294 183 C 254 188 243 200 238 238 C 233 200 222 188 182 183 C 222 178 233 166 238 128 Z',
    'M 141 266 C 144 292 151 299 178 303 C 151 307 144 314 141 340 C 138 314 131 307 104 303 C 131 299 138 292 141 266 Z',
    'M 886 602 C 890 636 900 645 934 650 C 900 655 890 664 886 698 C 882 664 872 655 838 650 C 872 645 882 636 886 602 Z',
]
# Mark bounds in artwork units (measured from the render, incl. strokes) and
# the radius from their centre that encloses every element (sparkle tips).
CENTER = (505.0, 498.5)
MAX_RADIUS = 491.0


def mark_group(color='#FFFFFF', ring=24, sparkles=True, gap=15):
    """The mark with genuinely transparent separation gaps (masks), so it
    works on any background and as an alpha-only monochrome icon."""
    sp = ''.join(f'<path d="{d}"/>' for d in SPARKLES) if sparkles else ''
    return f'''
  <defs>
    <mask id="ringMask" maskUnits="userSpaceOnUse" x="-2000" y="-2000" width="5000" height="5000">
      <rect x="-2000" y="-2000" width="5000" height="5000" fill="#fff"/>
      <path d="{Q_OUTER}" fill="#000" stroke="#000" stroke-width="{gap * 2}" stroke-linejoin="round"/>
    </mask>
    <mask id="qMask" maskUnits="userSpaceOnUse" x="-2000" y="-2000" width="5000" height="5000">
      <rect x="-2000" y="-2000" width="5000" height="5000" fill="#fff"/>
      <g transform="{RING_T}"><path d="{RING_FRONT}" fill="none" stroke="#000" stroke-width="{ring + gap * 2}"/></g>
    </mask>
  </defs>
  <g fill="{color}" stroke="none">
    <g mask="url(#ringMask)"><g transform="{RING_T}"><ellipse rx="455" ry="95" fill="none" stroke="{color}" stroke-width="{ring}"/></g></g>
    <path mask="url(#qMask)" fill-rule="evenodd" d="{Q_OUTER} {Q_INNER}"/>
    <g transform="{RING_T}"><path d="{RING_FRONT}" fill="none" stroke="{color}" stroke-width="{ring}"/></g>
    <g stroke="{color}" stroke-width="6" stroke-linejoin="round">{sp}</g>
  </g>'''


def placed(canvas, radius_fraction, **kw):
    """Mark scaled so its enclosing circle has radius canvas*radius_fraction, centred."""
    s = canvas * radius_fraction / MAX_RADIUS
    tx, ty = canvas / 2 - CENTER[0] * s, canvas / 2 - CENTER[1] * s
    return f'<g transform="translate({tx:.3f} {ty:.3f}) scale({s:.5f})">{mark_group(**kw)}</g>'


def svg(canvas, body, background=None, shape='square'):
    bg = ''
    if background:
        if shape == 'circle':
            bg = f'<circle cx="{canvas/2}" cy="{canvas/2}" r="{canvas/2}" fill="{background}"/>'
        elif shape == 'squircle':  # legacy launcher look (pre-API 26)
            r = canvas * 0.22
            bg = f'<rect width="{canvas}" height="{canvas}" rx="{r}" fill="{background}"/>'
        else:
            bg = f'<rect width="{canvas}" height="{canvas}" fill="{background}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{canvas}" height="{canvas}" '
            f'viewBox="0 0 {canvas} {canvas}">{bg}{body}</svg>')


def render(svg_text, out, opaque=False):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with tempfile.NamedTemporaryFile('w', suffix='.svg', delete=False) as f:
        f.write(svg_text)
        tmp = f.name
    fmt = 'PNG24:' if (opaque and out.endswith('.png')) else ('PNG32:' if out.endswith('.png') else '')
    args = ['magick', '-background', 'none', f'RSVG:{tmp}']
    if out.endswith('.webp'):
        args += ['-define', 'webp:lossless=true']
    subprocess.run(args + [fmt + out], check=True)
    os.unlink(tmp)


def p(*parts):
    return os.path.join(ROOT, *parts)


def main():
    # Canonical mark (1024 artwork space, cropped to its bounds).
    os.makedirs(p('assets', 'brand'), exist_ok=True)
    with open(p('assets', 'brand', 'quo-mark.svg'), 'w') as f:
        f.write('<svg xmlns="http://www.w3.org/2000/svg" viewBox="55 121 900 755" width="900" height="755">'
                f'{mark_group()}</svg>\n')

    # Expo / iOS assets (used by `expo prebuild` for iOS; Android below is
    # written directly because android/ is hand-maintained).
    render(svg(1024, placed(1024, 0.40, ring=28), INDIGO), p('assets', 'images', 'icon.png'), opaque=True)
    render(svg(1024, placed(1024, 0.30, ring=30)), p('assets', 'images', 'adaptive-icon-foreground.png'))
    render(svg(1024, placed(1024, 0.30, ring=30)), p('assets', 'images', 'adaptive-icon-monochrome.png'))
    render(svg(1024, placed(1024, 0.32, ring=26)), p('assets', 'images', 'splash-icon.png'))
    render(svg(96, placed(96, 0.47, ring=48, sparkles=False)), p('assets', 'images', 'notification-icon.png'))
    if '--store' in sys.argv:
        store = sys.argv[sys.argv.index('--store') + 1]
        os.makedirs(store, exist_ok=True)
        render(svg(512, placed(512, 0.40, ring=32), INDIGO), os.path.join(store, 'play-icon-512.png'), opaque=True)

    res = p('android', 'app', 'src', 'main', 'res')
    densities = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
    for name, k in densities.items():
        fg = round(108 * k)
        render(svg(fg, placed(fg, 0.30, ring=30)), os.path.join(res, f'mipmap-{name}', 'ic_launcher_foreground.webp'))
        render(svg(fg, placed(fg, 0.30, ring=30)), os.path.join(res, f'mipmap-{name}', 'ic_launcher_monochrome.webp'))
        legacy = round(48 * k)
        render(svg(legacy, placed(legacy, 0.36, ring=34), INDIGO, 'squircle'), os.path.join(res, f'mipmap-{name}', 'ic_launcher.webp'))
        render(svg(legacy, placed(legacy, 0.34, ring=34), INDIGO, 'circle'), os.path.join(res, f'mipmap-{name}', 'ic_launcher_round.webp'))
        splash = round(288 * k)
        render(svg(splash, placed(splash, 0.32, ring=26)), os.path.join(res, f'drawable-{name}', 'splashscreen_logo.png'))
        note = round(24 * k)
        render(svg(note, placed(note, 0.47, ring=48, sparkles=False)), os.path.join(res, f'drawable-{name}', 'notification_icon.png'))
    print('brand assets regenerated')


if __name__ == '__main__':
    main()
