// Writes src/models/architectures.ts: the model architectures the desktop engine's llama.cpp release can load, read
// from that release's src/llama-arch.cpp. Run after changing the release in apps/desktop/engine.lock.json:
//   node scripts/engine-architectures.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const lock = JSON.parse(readFileSync(new URL('../../desktop/engine.lock.json', import.meta.url), 'utf8'));
const source = await (await fetch(`https://raw.githubusercontent.com/ggml-org/llama.cpp/${lock.release}/src/llama-arch.cpp`)).text();
const table = source.slice(source.indexOf('LLM_ARCH_NAMES'), source.indexOf('};', source.indexOf('LLM_ARCH_NAMES')));
// Not models: the vision encoder, the drafters (Gemma's assistant, EAGLE-3, DFlash) and the "unknown" placeholder.
const skip = new Set(['clip', 'unknown', 'gemma4-assistant', 'eagle3', 'dflash']);
const names = [...table.matchAll(/\{\s*LLM_ARCH_\w+,\s*"([^"]+)"\s*\}/g)].map(m => m[1]).filter(name => !skip.has(name));
if (names.length < 100) throw new Error(`Only ${names.length} architectures found: has llama-arch.cpp changed shape?`);
const lines = [];
for (let i = 0; i < names.length; i += 8) lines.push(`  ${names.slice(i, i + 8).map(n => `'${n}'`).join(', ')},`);
writeFileSync(new URL('../src/models/architectures.ts', import.meta.url), `/**
 * The model architectures the desktop engine (llama.cpp ${lock.release}, apps/desktop/engine.lock.json) can load, as GGUF
 * files name them (general.architecture). Generated by scripts/engine-architectures.mjs from that release's
 * src/llama-arch.cpp; a test fails when the engine moves on and this list does not.
 */

export const ARCHITECTURES_RELEASE = '${lock.release}';

export const ENGINE_ARCHITECTURES: ReadonlySet<string> = new Set([
${lines.join('\n')}
]);
`);
console.log(`${names.length} architectures for ${lock.release}`);
